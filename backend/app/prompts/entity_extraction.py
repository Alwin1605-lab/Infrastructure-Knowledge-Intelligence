"""Entity extraction prompt templates for Building Knowledge Graph construction.

Defines prompts that instruct the LLM to extract structured entities
and relationships from building inspection reports, CPWD manuals,
structural audit reports, and other building engineering documents.

Domain: Buildings only (RCC, Residential, Commercial, Institutional,
        Government). No transportation or civil infrastructure entities.
"""

from app.prompts.base import BasePromptTemplate, PromptRegistry


@PromptRegistry.register
class EntityExtractionPrompts(BasePromptTemplate):
    """Prompt templates for Building Knowledge Graph entity and relationship extraction.

    Variables:
        - ``{text}``: The document chunk to extract entities from.
    """

    SYSTEM_PROMPT: str = (
        "You are a building engineering specialist tasked with extracting "
        "structured entities from technical building documents such as "
        "inspection reports, CPWD manuals, structural audit reports, and "
        "RCC building maintenance guides. Your goal is to identify and "
        "classify every relevant building engineering entity in the provided "
        "text according to the predefined entity types.\n\n"
        "## Entity Types\n\n"
        "- **Defect**: Any structural deficiency, damage, or deterioration "
        "in a building element (e.g., cracks, spalling, honeycombing, "
        "corrosion, water seepage, efflorescence, settlement, deflection, "
        "dampness, concrete deterioration).\n"
        "- **Cause**: The root cause or contributing factor behind a building "
        "defect (e.g., poor workmanship, improper curing, poor material "
        "quality, corrosion, foundation settlement, water ingress, thermal "
        "expansion, overloading, design errors, aging).\n"
        "- **Material**: Construction materials referenced in the building "
        "context (e.g., reinforced concrete, structural steel, brick masonry, "
        "cement mortar, waterproofing membrane, epoxy, plaster).\n"
        "- **RepairMethod**: Any remediation, repair, or rehabilitation "
        "technique applicable to buildings (e.g., epoxy injection, crack "
        "sealing, concrete jacketing, waterproofing, protective coating, "
        "re-plastering, grouting, structural strengthening, replacement, "
        "rehabilitation).\n"
        "- **Risk**: Identified risks or safety concerns related to the "
        "building (e.g., structural instability, load capacity reduction, "
        "collapse potential, habitability risk, water damage risk).\n"
        "- **Component**: Building structural or architectural components "
        "(e.g., foundation, footing, column, beam, slab, wall, roof, "
        "staircase, door, window, plinth, lintel, parapet, balcony).\n\n"
        "## Output Format\n\n"
        "Return a JSON object with a single key \"entities\", containing an "
        "array of extracted entities. Each entity must have:\n"
        "- \"name\": The entity's canonical name (normalized, lowercase).\n"
        "- \"type\": One of the six entity types listed above.\n"
        "- \"mentions\": Array of exact text spans where this entity appears.\n"
        "- \"attributes\": Object with any relevant attributes (severity, "
        "building location, floor level, measurement, etc.).\n\n"
        "## Scope Restriction\n\n"
        "Extract ONLY entities related to buildings. Do NOT extract entities "
        "related to roads, bridges, tunnels, dams, pavements, or any "
        "transportation infrastructure. If such content appears in the text, "
        "ignore it.\n\n"
        "If no entities of a given type are found, omit that type. "
        "Return an empty \"entities\" array if the text contains no "
        "relevant building engineering entities."
    )

    EXTRACTION_TEMPLATE: str = (
        "Extract all building engineering entities from the following text. "
        "Return ONLY valid JSON matching the schema below.\n\n"
        "## Text to Analyze\n\n"
        "{text}\n\n"
        "## Expected JSON Schema\n\n"
        "```json\n"
        "{{\n"
        "  \"entities\": [\n"
        "    {{\n"
        "      \"name\": \"entity name (lowercase, canonical form)\",\n"
        "      \"type\": \"Defect | Cause | Material | RepairMethod | Risk | Component\",\n"
        "      \"mentions\": [\"exact text span 1\", \"exact text span 2\"],\n"
        "      \"attributes\": {{\n"
        "        \"severity\": \"high | medium | low (if applicable)\",\n"
        "        \"location\": \"building location or element (e.g., ground floor column, roof slab)\",\n"
        "        \"measurement\": \"quantitative data (if available, e.g., crack width 2mm)\"\n"
        "      }}\n"
        "    }}\n"
        "  ]\n"
        "}}\n"
        "```\n\n"
        "## Building-Specific Entity Examples\n\n"
        "Defects: cracks, spalling, honeycombing, corrosion, water seepage, "
        "efflorescence, settlement, deflection, dampness, concrete deterioration\n\n"
        "Causes: poor workmanship, improper curing, poor material quality, "
        "corrosion, foundation settlement, water ingress, thermal expansion, "
        "overloading, design errors, aging\n\n"
        "Components: foundation, footing, column, beam, slab, wall, roof, "
        "staircase, door, window, plinth, lintel, parapet, balcony\n\n"
        "RepairMethods: epoxy injection, crack sealing, concrete jacketing, "
        "waterproofing, protective coating, re-plastering, grouting, "
        "structural strengthening, replacement, rehabilitation\n\n"
        "Important:\n"
        "- Normalize entity names to lowercase canonical forms.\n"
        "- Include ALL mentions of each entity, even if repeated.\n"
        "- Only include attributes that are explicitly stated in the text.\n"
        "- Do NOT infer or fabricate information not present in the text.\n"
        "- Do NOT extract any transportation or civil infrastructure entities."
    )

    RELATIONSHIP_TEMPLATE: str = (
        "Given the following extracted building engineering entities, identify "
        "all relationships between them. Return ONLY valid JSON.\n\n"
        "## Extracted Entities\n\n"
        "{text}\n\n"
        "## Relationship Types\n\n"
        "- **CAUSED_BY**: A Defect is caused by a Cause "
        "(e.g., spalling CAUSED_BY corrosion, cracks CAUSED_BY overloading).\n"
        "- **REPAIRED_BY**: A Defect is repaired by a RepairMethod "
        "(e.g., honeycombing REPAIRED_BY grouting, cracks REPAIRED_BY epoxy injection).\n"
        "- **AFFECTS**: A Defect or Risk affects a Component "
        "(e.g., corrosion AFFECTS column reinforcement, seepage AFFECTS slab).\n"
        "- **MADE_OF**: A Component is made of a Material "
        "(e.g., column MADE_OF reinforced concrete, wall MADE_OF brick masonry).\n"
        "- **MITIGATES**: A RepairMethod mitigates a Risk or Defect "
        "(e.g., waterproofing MITIGATES water seepage risk).\n"
        "- **LOCATED_AT**: An entity is spatially located at a building Component "
        "(e.g., spalling LOCATED_AT ground floor column).\n"
        "- **PART_OF**: A Component is part of a larger building system "
        "(e.g., footing PART_OF foundation, lintel PART_OF wall).\n\n"
        "## Expected JSON Schema\n\n"
        "```json\n"
        "{{\n"
        "  \"relationships\": [\n"
        "    {{\n"
        "      \"source\": \"source entity name\",\n"
        "      \"source_type\": \"entity type\",\n"
        "      \"relationship\": \"CAUSED_BY | REPAIRED_BY | AFFECTS | MADE_OF | MITIGATES | LOCATED_AT | PART_OF\",\n"
        "      \"target\": \"target entity name\",\n"
        "      \"target_type\": \"entity type\",\n"
        "      \"evidence\": \"brief text excerpt supporting this relationship\"\n"
        "    }}\n"
        "  ]\n"
        "}}\n"
        "```\n\n"
        "Only include relationships with clear textual evidence. Do NOT "
        "infer relationships that are not supported by the source text."
    )
