"""Pydantic schemas for the Agentic Pipeline response (Phase 6).

AgentPipelineResponse wraps the full Phase 5 ChatResponse and adds:
    - execution_trace: Per-agent diagnostics (status, time_ms, confidence, reason)
    - report: Structured engineering report text
    - overall_confidence: Weighted average of all agent confidence scores
    - pipeline metadata: session_id, version, total timing

The ChatResponse inside rag_response is unchanged from Phase 5.
"""

from typing import Literal, Optional

from pydantic import BaseModel, Field

from app.schemas.chat import ChatResponse


class AgentExecutionStepSchema(BaseModel):
    """Schema for a single agent's execution record in the pipeline trace.

    This is the externally visible version of the internal AgentExecutionStep dataclass.
    Each step tells the caller:
        - WHAT the agent did (agent name)
        - WHETHER it succeeded (status)
        - HOW LONG it took (time_ms)
        - HOW CONFIDENT it was in its output (confidence)
        - WHY it made its decision (reason)
    """

    agent: str = Field(
        ...,
        description="Name of the agent that executed this step.",
        examples=["QueryAnalysisAgent", "RetrievalAgent", "KGReasoningAgent"],
    )
    status: Literal["success", "skipped", "failed"] = Field(
        ...,
        description="Outcome of this agent's execution.",
    )
    time_ms: float = Field(
        ...,
        ge=0.0,
        description="Wall-clock execution time in milliseconds.",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Agent-specific confidence score (0.0 = no confidence, 1.0 = certain). "
            "Independent of the overall RAG confidence score."
        ),
    )
    reason: str = Field(
        ...,
        description=(
            "Human-readable explanation of what the agent decided and why. "
            "For example: 'Expanded defect spalling to related corrosion and exposed reinforcement.'"
        ),
    )
    error: Optional[str] = Field(
        default=None,
        description="Error message if status is failed.",
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "agent": "KGReasoningAgent",
                    "status": "success",
                    "time_ms": 38.2,
                    "confidence": 0.87,
                    "reason": "Expanded defect 'spalling' to related corrosion, exposed reinforcement, and concrete delamination. Discovered 4 new relationships through multi-hop traversal.",
                    "error": None,
                }
            ]
        }
    }


class AgentPipelineRequest(BaseModel):
    """Request schema for the Agentic Pipeline endpoint."""

    question: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="Building engineering question to process through the full agent pipeline.",
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of document chunks to retrieve for RAG context.",
    )
    include_kg: bool = Field(
        default=True,
        description="Whether to run the KG Reasoning Agent for enriched graph context.",
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "question": "What causes spalling in RCC columns and how should it be repaired?",
                    "top_k": 5,
                    "include_kg": True,
                }
            ]
        }
    }


class AgentPipelineResponse(BaseModel):
    """Complete response from the 5-agent Building Knowledge Intelligence Pipeline.

    Contains:
        - Full Phase 5 ChatResponse (answer, sources, KG context, confidence)
        - Structured engineering report from ReportAgent
        - Per-agent execution trace (status, time, confidence, reason for each agent)
        - Pipeline metadata (session ID, version, total timing, overall confidence)
    """

    session_id: str = Field(
        ...,
        description="Unique ID for this pipeline execution trace.",
    )
    question: str = Field(
        ...,
        description="Original user question.",
    )
    rag_response: Optional[ChatResponse] = Field(
        default=None,
        description="Full structured Phase 5 RAG response with answer, sources, and KG context.",
    )
    report: str = Field(
        default="",
        description="Structured engineering assessment report generated by ReportAgent.",
    )
    execution_trace: list[AgentExecutionStepSchema] = Field(
        default_factory=list,
        description=(
            "Per-agent execution trace with status, timing, confidence score, and reason. "
            "Shows exactly which agents ran, what they decided, and how confident they were."
        ),
    )
    total_agents_run: int = Field(
        ...,
        description="Number of agents that executed successfully.",
    )
    total_pipeline_ms: float = Field(
        ...,
        description="Total wall-clock pipeline execution time in milliseconds.",
    )
    pipeline_version: str = Field(
        ...,
        description="Agentic pipeline version.",
    )
    overall_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Weighted average confidence across all agents that ran successfully. "
            "Separate from the RAG-level confidence score in rag_response.confidence."
        ),
    )
    domain_valid: bool = Field(
        default=True,
        description="False if the query was rejected as outside the building domain.",
    )
    query_intent: Optional[str] = Field(
        default=None,
        description="Classified intent of the query (e.g., 'defect_diagnosis', 'repair_recommendation').",
    )
    enriched_kg_available: bool = Field(
        default=False,
        description="True if KGReasoningAgent found enriched multi-hop context.",
    )

