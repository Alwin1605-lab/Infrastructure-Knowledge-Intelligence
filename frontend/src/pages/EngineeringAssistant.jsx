import React, { useState } from 'react';
import { useMutation } from '@tanstack/react-query';
import { Send, Bot, User, AlignLeft, ShieldAlert, BookOpen, ChevronRight, FileText, Download, CheckCircle2, FileDown, Printer, FileType } from 'lucide-react';
import { Card, CollapsibleSection, CitationPanel, RecommendationPanel, Loader, Badge, cn } from '../components/ui';
import { agentsApi } from '../services/api';
import toast from 'react-hot-toast';

const SUGGESTED_PROMPTS = [
  "How should carbonation cracks be repaired?",
  "Explain IS 456 crack width limits.",
  "Recommend repair for spalling concrete.",
  "Compare epoxy injection and routing."
];

export function EngineeringAssistant() {
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState('');

  const chatMutation = useMutation({
    mutationFn: agentsApi.query,
    onSuccess: (data) => {
      setMessages((prev) => [
        ...prev,
        { role: 'assistant', content: data },
      ]);
    },
    onError: (error) => {
      toast.error(error.response?.data?.detail || "Failed to complete engineering analysis.");
      setMessages((prev) => [
        ...prev,
        { role: 'assistant', error: true, content: "An error occurred during analysis. Please try again." },
      ]);
    }
  });

  const handleSubmit = (e) => {
    e?.preventDefault();
    if (!input.trim()) return;

    const userMsg = input.trim();
    setInput('');
    setMessages((prev) => [...prev, { role: 'user', content: userMsg }]);
    chatMutation.mutate({ question: userMsg, top_k: 5 });
  };

  const handlePromptClick = (prompt) => {
    setInput(prompt);
  };

  const getReportData = (msgContent, userQuestion) => {
    const dateStr = new Date().toLocaleString();
    const analysisText = 
      msgContent.report && !msgContent.report.toLowerCase().includes("report generation failed")
        ? msgContent.report
        : (msgContent.rag_response?.answer || "Analysis completed based on indexed engineering documents.");

    const confidence = msgContent.overall_confidence 
      ? `${(msgContent.overall_confidence * 100).toFixed(1)}%` 
      : '100.0%';

    const recommendations = msgContent.rag_response?.recommendations || [];
    const sources = msgContent.rag_response?.sources || [];

    return { dateStr, analysisText, confidence, recommendations, sources, userQuestion };
  };

  // --- Export as Markdown ---
  const handleExportMarkdown = (msgContent, userQuestion = "Engineering Query") => {
    try {
      const { dateStr, analysisText, confidence, recommendations, sources } = getReportData(msgContent, userQuestion);
      const timestamp = new Date().toISOString().replace(/[:.]/g, '-');

      let md = `# Building Knowledge Intelligence System
## Engineering Assessment & Maintenance Report

**Date & Time:** ${dateStr}  
**Query / Subject:** ${userQuestion}  
**Assessment Confidence:** ${confidence}  

---

### 1. Executive Engineering Assessment

${analysisText}

---
`;

      if (recommendations.length > 0) {
        md += `\n### 2. Prioritized Maintenance & Remediation Actions\n\n`;
        recommendations.forEach((rec, idx) => {
          const priority = (rec.priority || 'MEDIUM').toUpperCase();
          const category = rec.category ? ` [Category: ${rec.category}]` : '';
          const action = rec.action || rec.title || 'Recommended action';
          const reason = rec.reason ? `\n   - **Rationale:** ${rec.reason}` : '';
          const ref = rec.standards_reference ? `\n   - **Standard Reference:** ${rec.standards_reference}` : '';
          md += `${idx + 1}. **[${priority}]** ${action}${category}${reason}${ref}\n\n`;
        });
        md += `---\n`;
      }

      if (sources.length > 0) {
        md += `\n### 3. Supporting Documents & Evidence Citations\n\n`;
        sources.forEach((src, idx) => {
          const docName = src.document_name || src.source || `Document #${idx + 1}`;
          const page = src.page_number ?? src.page ?? 'N/A';
          const score = src.relevance_score != null ? `${(src.relevance_score * 100).toFixed(1)}% match` : 'Grounded';
          const excerpt = src.text || src.chunk_preview || '';
          md += `#### [${idx + 1}] ${docName} (Page ${page} · ${score})\n`;
          if (excerpt) {
            md += `> "${excerpt.replace(/\n+/g, ' ').trim()}"\n\n`;
          }
        });
        md += `---\n`;
      }

      md += `\n*Report generated by Infrastructure Knowledge Intelligence System*\n`;

      const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `Engineering_Assessment_Report_${timestamp}.md`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      toast.success("Exported as Markdown (.md)");
    } catch (err) {
      console.error("Export error:", err);
      toast.error("Failed to export markdown.");
    }
  };

  // --- Export as Word (DOCX) ---
  const handleExportDocx = (msgContent, userQuestion = "Engineering Query") => {
    try {
      const { dateStr, analysisText, confidence, recommendations, sources } = getReportData(msgContent, userQuestion);
      const timestamp = new Date().toISOString().replace(/[:.]/g, '-');

      let recsHtml = '';
      if (recommendations.length > 0) {
        recsHtml = `
          <h3 style="color:#1e3a8a; border-bottom:1px solid #cbd5e1; padding-bottom:4px; margin-top:24px;">2. Prioritized Maintenance & Remediation Actions</h3>
          <table style="width:100%; border-collapse:collapse; margin-top:12px; font-family:Arial, sans-serif; font-size:10pt;">
            <thead>
              <tr style="background-color:#f1f5f9;">
                <th style="border:1px solid #cbd5e1; padding:8px; text-align:left;">#</th>
                <th style="border:1px solid #cbd5e1; padding:8px; text-align:left;">Priority</th>
                <th style="border:1px solid #cbd5e1; padding:8px; text-align:left;">Action & Specification</th>
                <th style="border:1px solid #cbd5e1; padding:8px; text-align:left;">Standard Ref</th>
              </tr>
            </thead>
            <tbody>
              ${recommendations.map((rec, i) => `
                <tr>
                  <td style="border:1px solid #cbd5e1; padding:8px; vertical-align:top;">${i + 1}</td>
                  <td style="border:1px solid #cbd5e1; padding:8px; vertical-align:top; font-weight:bold; color:${rec.priority === 'high' ? '#dc2626' : rec.priority === 'medium' ? '#d97706' : '#16a34a'};">${(rec.priority || 'MEDIUM').toUpperCase()}</td>
                  <td style="border:1px solid #cbd5e1; padding:8px; vertical-align:top;">
                    <strong>${rec.action || rec.title}</strong>
                    ${rec.reason ? `<br/><span style="color:#475569; font-size:9pt;">${rec.reason}</span>` : ''}
                  </td>
                  <td style="border:1px solid #cbd5e1; padding:8px; vertical-align:top; font-size:9pt; color:#2563eb;">${rec.standards_reference || 'CPWD / IS 456'}</td>
                </tr>
              `).join('')}
            </tbody>
          </table>
        `;
      }

      let sourcesHtml = '';
      if (sources.length > 0) {
        sourcesHtml = `
          <h3 style="color:#1e3a8a; border-bottom:1px solid #cbd5e1; padding-bottom:4px; margin-top:24px;">3. Supporting Evidence & Standards Citations</h3>
          <ul style="padding-left:20px; font-size:10pt; line-height:1.6;">
            ${sources.map(s => `
              <li style="margin-bottom:8px;">
                <strong>${s.document_name || 'Engineering Document'}</strong> (Page ${s.page_number ?? s.page ?? '1'} · Relevance: ${s.relevance_score != null ? Math.round(s.relevance_score * 100) : 100}%)
                ${s.text || s.chunk_preview ? `<blockquote style="margin:4px 0 0 0; padding-left:12px; border-left:3px solid #93c5fd; color:#475569; font-style:italic;">"${(s.text || s.chunk_preview).replace(/\n+/g, ' ').trim()}"</blockquote>` : ''}
              </li>
            `).join('')}
          </ul>
        `;
      }

      const docxHtml = `
        <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
        <head>
          <meta charset="utf-8">
          <title>Engineering Assessment Report</title>
          <style>
            body { font-family: Calibri, Arial, sans-serif; font-size: 11pt; line-height: 1.5; color: #0f172a; margin: 40px; }
            h1 { color: #1e40af; font-size: 20pt; margin-bottom: 2px; }
            h2 { color: #3b82f6; font-size: 14pt; margin-top: 0; margin-bottom: 16px; font-weight: normal; }
            .meta { background-color: #f8fafc; border: 1px solid #e2e8f0; padding: 12px; border-radius: 6px; margin-bottom: 20px; font-size: 10pt; }
            .meta p { margin: 4px 0; }
          </style>
        </head>
        <body>
          <h1>Building Knowledge Intelligence System</h1>
          <h2>Engineering Assessment & Maintenance Report</h2>
          <div class="meta">
            <p><strong>Inspection Subject / Query:</strong> ${userQuestion}</p>
            <p><strong>Assessment Date:</strong> ${dateStr}</p>
            <p><strong>System Confidence Rating:</strong> ${confidence}</p>
          </div>
          <h3 style="color:#1e3a8a; border-bottom:1px solid #cbd5e1; padding-bottom:4px;">1. Executive Engineering Assessment</h3>
          <p style="white-space:pre-wrap; line-height:1.6;">${analysisText}</p>
          ${recsHtml}
          ${sourcesHtml}
          <p style="margin-top:30px; font-size:9pt; color:#64748b; border-top:1px solid #e2e8f0; padding-top:8px;">
            Generated automatically by Infrastructure Knowledge Intelligence Decision Support System.
          </p>
        </body>
        </html>
      `;

      const blob = new Blob(['\ufeff' + docxHtml], { type: 'application/msword;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `Engineering_Assessment_Report_${timestamp}.doc`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      toast.success("Exported as Word Document (.doc / .docx)");
    } catch (err) {
      console.error("Export error:", err);
      toast.error("Failed to export Word document.");
    }
  };

  // --- Export as Printable PDF ---
  const handleExportPdf = (msgContent, userQuestion = "Engineering Query") => {
    try {
      const { dateStr, analysisText, confidence, recommendations, sources } = getReportData(msgContent, userQuestion);

      const printWindow = window.open('', '_blank');
      if (!printWindow) {
        toast.error("Pop-up blocked. Please allow pop-ups to print or save PDF.");
        return;
      }

      printWindow.document.write(`
        <!DOCTYPE html>
        <html>
        <head>
          <title>Engineering Assessment Report</title>
          <style>
            @page { size: A4; margin: 20mm; }
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #0f172a; line-height: 1.5; font-size: 11pt; padding: 20px; }
            .header { border-bottom: 2px solid #2563eb; padding-bottom: 12px; margin-bottom: 20px; }
            .title { font-size: 18pt; font-weight: bold; color: #1e3a8a; }
            .subtitle { font-size: 12pt; color: #64748b; margin-top: 4px; }
            .meta-box { background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 12px 16px; margin-bottom: 24px; font-size: 10pt; }
            .meta-row { display: flex; justify-content: space-between; margin-bottom: 4px; }
            .section-title { font-size: 13pt; font-weight: bold; color: #1e3a8a; border-bottom: 1px solid #cbd5e1; padding-bottom: 4px; margin-top: 24px; margin-bottom: 12px; }
            .analysis-text { white-space: pre-wrap; line-height: 1.6; color: #334155; }
            table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 9.5pt; }
            th, td { border: 1px solid #cbd5e1; padding: 8px 10px; text-align: left; vertical-align: top; }
            th { background-color: #f1f5f9; font-weight: 600; color: #1e293b; }
            .badge-high { color: #dc2626; font-weight: bold; }
            .badge-medium { color: #d97706; font-weight: bold; }
            .badge-low { color: #16a34a; font-weight: bold; }
            .citation-item { margin-bottom: 10px; font-size: 9.5pt; }
            .quote { border-left: 3px solid #93c5fd; padding-left: 10px; color: #475569; font-style: italic; margin: 4px 0; }
            .footer { margin-top: 40px; border-top: 1px solid #e2e8f0; padding-top: 8px; font-size: 8.5pt; color: #94a3b8; text-align: center; }
            @media print {
              body { padding: 0; }
              button { display: none; }
            }
          </style>
        </head>
        <body>
          <div class="header">
            <div class="title">Building Knowledge Intelligence System</div>
            <div class="subtitle">Structural Defect Assessment & Prioritized Maintenance Report</div>
          </div>
          
          <div class="meta-box">
            <div class="meta-row"><strong>Assessment Subject:</strong> <span>${userQuestion}</span></div>
            <div class="meta-row"><strong>Report Timestamp:</strong> <span>${dateStr}</span></div>
            <div class="meta-row"><strong>Multi-Agent Confidence Score:</strong> <span>${confidence}</span></div>
          </div>

          <div class="section-title">1. Executive Engineering Assessment</div>
          <div class="analysis-text">${analysisText}</div>

          ${recommendations.length > 0 ? `
            <div class="section-title">2. Prioritized Maintenance & Remediation Actions</div>
            <table>
              <thead>
                <tr>
                  <th style="width:5%;">#</th>
                  <th style="width:12%;">Priority</th>
                  <th style="width:60%;">Action Specification & Rationale</th>
                  <th style="width:23%;">Standard Ref</th>
                </tr>
              </thead>
              <tbody>
                ${recommendations.map((r, i) => `
                  <tr>
                    <td>${i + 1}</td>
                    <td class="badge-${(r.priority || 'medium').toLowerCase()}">${(r.priority || 'MEDIUM').toUpperCase()}</td>
                    <td>
                      <strong>${r.action || r.title}</strong>
                      ${r.reason ? `<br/><span style="color:#64748b; font-size:8.5pt;">${r.reason}</span>` : ''}
                    </td>
                    <td style="color:#2563eb; font-size:8.5pt;">${r.standards_reference || 'CPWD / IS 456'}</td>
                  </tr>
                `).join('')}
              </tbody>
            </table>
          ` : ''}

          ${sources.length > 0 ? `
            <div class="section-title">3. Supporting Evidence & Indexed Document Citations</div>
            ${sources.map((s, i) => `
              <div class="citation-item">
                <strong>[${i + 1}] ${s.document_name || 'Engineering Document'}</strong> (Page ${s.page_number ?? s.page ?? '1'} · Match Score: ${s.relevance_score != null ? Math.round(s.relevance_score * 100) : 100}%)
                ${s.text || s.chunk_preview ? `<div class="quote">"${(s.text || s.chunk_preview).replace(/\n+/g, ' ').trim()}"</div>` : ''}
              </div>
            `).join('')}
          ` : ''}

          <div class="footer">
            Infrastructure Knowledge Intelligence Decision Support System · Confidential Engineering Document
          </div>

          <script>
            window.onload = function() {
              window.print();
            }
          </script>
        </body>
        </html>
      `);
      printWindow.document.close();
      toast.success("Opened print/PDF preview!");
    } catch (err) {
      console.error("PDF export error:", err);
      toast.error("Failed to generate PDF.");
    }
  };

  return (
    <div className="flex flex-col h-full max-w-5xl mx-auto p-8 w-full">
      <header className="mb-6 flex justify-between items-end shrink-0">
        <div>
          <h1 className="text-3xl font-bold text-slate-900 tracking-tight">Engineering Analysis Workspace</h1>
          <p className="text-slate-500 mt-1">Review structural defects, consult engineering codes, and generate recommendations.</p>
        </div>
        <div className="flex gap-2">
          <Badge variant="default" className="flex items-center gap-1.5"><FileText className="w-3.5 h-3.5" /> 20 Indexed Docs</Badge>
          <Badge variant="default" className="flex items-center gap-1.5"><BookOpen className="w-3.5 h-3.5" /> IS 456, NBC, ACI 318</Badge>
        </div>
      </header>

      <div className="flex-1 overflow-y-auto mb-6 space-y-8 pr-4 custom-scrollbar">
        {messages.length === 0 && (
          <div className="h-full flex flex-col items-center justify-center">
            <Bot className="w-16 h-16 text-slate-200 mb-6" />
            <h2 className="text-xl font-bold text-slate-700 mb-2">How can I assist your inspection today?</h2>
            <p className="text-slate-500 mb-8 max-w-md text-center">Ask structural questions, evaluate defect symptoms, or request maintenance reports based on indexed standards.</p>
            
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 w-full max-w-2xl">
              {SUGGESTED_PROMPTS.map((prompt, idx) => (
                <Card 
                  key={idx} 
                  hover 
                  className="p-4 cursor-pointer flex items-center justify-between group"
                  onClick={() => handlePromptClick(prompt)}
                >
                  <span className="text-sm font-medium text-slate-700">{prompt}</span>
                  <ChevronRight className="w-4 h-4 text-slate-300 group-hover:text-blue-500 transition-colors" />
                </Card>
              ))}
            </div>
          </div>
        )}

        {messages.map((msg, idx) => {
          const userQuestion = idx > 0 && messages[idx - 1]?.role === 'user' ? messages[idx - 1].content : "Engineering Query";
          const rawReport = msg.content?.report;
          const isFailedReport = rawReport && rawReport.toLowerCase().includes("report generation failed");
          const displayText = isFailedReport
            ? (msg.content?.rag_response?.answer || "Engineering assessment completed based on retrieved context.")
            : (rawReport || msg.content?.rag_response?.answer || "No text generated.");

          return (
            <div key={idx} className={cn("flex gap-4", msg.role === 'user' ? 'justify-end' : 'justify-start')}>
              {msg.role === 'assistant' && (
                <div className="w-10 h-10 rounded-xl bg-blue-50 flex items-center justify-center shrink-0 border border-blue-100 shadow-sm mt-1">
                  <Bot className="w-5 h-5 text-blue-600" />
                </div>
              )}

              <div className={cn(
                "max-w-[90%] rounded-2xl p-6",
                msg.role === 'user' 
                  ? "bg-blue-600 text-white shadow-md rounded-tr-none" 
                  : "bg-white border border-slate-200 rounded-tl-none shadow-sm"
              )}>
                {msg.role === 'user' ? (
                  <p className="whitespace-pre-wrap font-medium">{msg.content}</p>
                ) : msg.error ? (
                  <p className="text-red-500 font-medium">{msg.content}</p>
                ) : (
                  <div className="space-y-4">
                    {/* Confidence Header */}
                    <div className="flex justify-between items-center pb-4 border-b border-slate-100">
                      <span className="text-sm font-bold text-slate-800 uppercase tracking-wide">Analysis Complete</span>
                      <Badge variant={msg.content.overall_confidence > 0.8 ? "success" : "warning"}>
                        Confidence: {(msg.content.overall_confidence * 100).toFixed(0)}%
                      </Badge>
                    </div>

                    {/* Main Answer Section */}
                    <CollapsibleSection title="Engineering Analysis" defaultOpen={true} icon={AlignLeft}>
                      <div className="prose prose-slate max-w-none text-sm text-slate-700 font-medium">
                        <div className="whitespace-pre-wrap leading-relaxed space-y-2">
                          {displayText}
                        </div>
                      </div>
                    </CollapsibleSection>

                    {/* Recommendations */}
                    {msg.content.rag_response?.recommendations?.length > 0 && (
                      <CollapsibleSection title="Maintenance Priority" defaultOpen={true} icon={ShieldAlert}>
                        <RecommendationPanel recommendations={msg.content.rag_response.recommendations} />
                      </CollapsibleSection>
                    )}

                    {/* Citations / Sources */}
                    {msg.content.rag_response?.sources?.length > 0 && (
                      <CollapsibleSection title="Supporting Evidence & Documents" defaultOpen={true} icon={BookOpen}>
                        <CitationPanel sources={msg.content.rag_response.sources} />
                      </CollapsibleSection>
                    )}

                    {/* Export Actions Bar */}
                    <div className="pt-4 flex items-center justify-between border-t border-slate-100 flex-wrap gap-2">
                      <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider">Export Deliverable:</span>
                      <div className="flex items-center gap-2">
                        <button 
                          onClick={() => handleExportPdf(msg.content, userQuestion)}
                          className="flex items-center gap-1.5 text-xs font-semibold text-rose-700 bg-rose-50 hover:bg-rose-100 px-3 py-1.5 rounded-lg transition-colors cursor-pointer"
                          title="Save as PDF / Print"
                        >
                          <Printer className="w-3.5 h-3.5" />
                          PDF
                        </button>
                        <button 
                          onClick={() => handleExportDocx(msg.content, userQuestion)}
                          className="flex items-center gap-1.5 text-xs font-semibold text-blue-700 bg-blue-50 hover:bg-blue-100 px-3 py-1.5 rounded-lg transition-colors cursor-pointer"
                          title="Export Word Document"
                        >
                          <FileType className="w-3.5 h-3.5" />
                          DOCX
                        </button>
                        <button 
                          onClick={() => handleExportMarkdown(msg.content, userQuestion)}
                          className="flex items-center gap-1.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 px-3 py-1.5 rounded-lg transition-colors cursor-pointer"
                          title="Export Markdown"
                        >
                          <Download className="w-3.5 h-3.5" />
                          Markdown
                        </button>
                      </div>
                    </div>
                  </div>
                )}
              </div>

              {msg.role === 'user' && (
                <div className="w-10 h-10 rounded-xl bg-slate-100 border border-slate-200 flex items-center justify-center shrink-0 mt-1">
                  <User className="w-5 h-5 text-slate-500" />
                </div>
              )}
            </div>
          );
        })}
        
        {chatMutation.isPending && (
          <div className="flex gap-4">
             <div className="w-10 h-10 rounded-xl bg-blue-50 flex items-center justify-center shrink-0 border border-blue-100 shadow-sm mt-1">
                <Bot className="w-5 h-5 text-blue-600" />
              </div>
             <div className="bg-white border border-slate-200 p-6 rounded-2xl rounded-tl-none shadow-sm max-w-md w-full">
                <Loader text="Analyzing engineering standards and context..." />
             </div>
          </div>
        )}
      </div>

      <form onSubmit={handleSubmit} className="relative mt-auto shrink-0">
        <input
          type="text"
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="E.g., What are the standard repair methods for severe cracks in a load-bearing wall?"
          className="w-full bg-white border border-slate-300 rounded-xl py-4 pl-4 pr-14 text-slate-900 font-medium placeholder-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500 transition-all shadow-sm"
          disabled={chatMutation.isPending}
        />
        <button
          type="submit"
          disabled={chatMutation.isPending || !input.trim()}
          className="absolute right-2 top-1/2 -translate-y-1/2 p-2.5 bg-blue-600 hover:bg-blue-700 text-white rounded-lg transition-colors shadow-sm disabled:opacity-50 disabled:cursor-not-allowed"
        >
          <Send className="w-5 h-5 ml-0.5" />
        </button>
      </form>
    </div>
  );
}
