import React, { useState } from 'react';
import { Card, Badge } from '../components/ui';
import { FileBarChart, Download, ExternalLink, Calendar, Plus, Bot, CheckCircle2 } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useDocuments } from '../hooks/useDocumentsQuery';
import toast from 'react-hot-toast';

export function Reports() {
  const navigate = useNavigate();
  const { data: documentsData } = useDocuments({ limit: 100 });
  const docs = documentsData?.documents || [];

  const defaultReports = [
    { 
      id: 'rep-01', 
      title: 'Structural Condition Assessment — Reinforced Concrete Columns with Spalling', 
      date: new Date().toISOString(), 
      risk: 'high', 
      type: 'Defect Analysis',
      summary: 'Analysis of compressive cover spalling, rebar exposure, and high-priority repair recommendations using polymer modified mortar and carbonation mitigation according to CPWD/IS 456.',
      recommendations: 4
    },
    { 
      id: 'rep-02', 
      title: 'Seismic Vulnerability & Retrofitting Report — Exterior Beam-Column Joints', 
      date: new Date(Date.now() - 86400000 * 2).toISOString(), 
      risk: 'medium', 
      type: 'Seismic Evaluation',
      summary: 'Evaluation of joint shear distress under cyclic lateral loading. Recommendation for CFRP composite wrapping and PC bar confinement to enhance joint shear ductility.',
      recommendations: 5
    },
    { 
      id: 'rep-03', 
      title: 'Deep Foundation & Soil-Structure Interaction Engineering Report', 
      date: new Date(Date.now() - 86400000 * 5).toISOString(), 
      risk: 'low', 
      type: 'Geotechnical',
      summary: 'Bearing capacity analysis of shallow footing on heterogeneous granular soil. Subgrade reaction modulus and settlement estimation compliance report.',
      recommendations: 3
    }
  ];

  const handleExportReport = (report) => {
    const content = `# Building Knowledge Intelligence System
# Engineering Report: ${report.title}

**Report ID:** ${report.id}  
**Date:** ${new Date(report.date).toLocaleDateString()}  
**Risk Level:** ${report.risk.toUpperCase()}  
**Report Type:** ${report.type}  

---

## Executive Summary
${report.summary}

---

## Actions & Maintenance Plan
1. **[HIGH]** Implement immediate non-destructive testing (UPV / Rebound Hammer) to evaluate internal core integrity.
2. **[HIGH]** Remove loose and delaminated concrete cover around reinforcing bars. Apply zinc-rich anti-corrosion primer.
3. **[MEDIUM]** Apply polymer-modified structural mortar or epoxy mortar patch repair.
4. **[MONITORING]** Install crack monitoring telltales and re-assess within 3 months.

---
*Report generated by Infrastructure Knowledge Intelligence System*
`;
    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${report.id}_Engineering_Report.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    toast.success(`Exported ${report.title.slice(0, 30)}...`);
  };

  return (
    <div className="p-8 max-w-7xl mx-auto w-full space-y-6">
      <div className="flex justify-between items-center mb-4">
        <div>
          <h1 className="text-3xl font-bold text-slate-900 tracking-tight">Engineering Reports</h1>
          <p className="text-slate-500 mt-1 text-lg">Comprehensive structural assessment summaries and maintenance plans generated by the multi-agent AI pipeline.</p>
        </div>
        <button 
          onClick={() => navigate('/assistant')}
          className="bg-blue-600 hover:bg-blue-700 text-white px-5 py-2.5 rounded-xl font-medium transition-colors shadow-sm flex items-center gap-2 cursor-pointer"
        >
          <Bot className="w-5 h-5" />
          Generate New Report in Assistant
        </button>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {defaultReports.map(report => (
          <Card key={report.id} hover className="p-6 flex flex-col justify-between">
            <div>
              <div className="flex justify-between items-start mb-4">
                <Badge variant={report.risk === 'high' ? 'danger' : report.risk === 'medium' ? 'warning' : 'success'}>
                  {report.risk.toUpperCase()} RISK
                </Badge>
                <Badge variant="default">{report.type}</Badge>
              </div>
              <h3 className="text-xl font-bold text-slate-900 mb-2 leading-snug">{report.title}</h3>
              <p className="text-slate-600 text-sm leading-relaxed mb-4">{report.summary}</p>
              
              <div className="flex items-center gap-4 text-slate-500 text-xs font-medium mb-6">
                <span className="flex items-center gap-1.5">
                  <Calendar className="w-4 h-4 text-slate-400" />
                  {new Date(report.date).toLocaleDateString()}
                </span>
                <span className="flex items-center gap-1.5 text-blue-600 font-semibold">
                  <CheckCircle2 className="w-4 h-4 text-emerald-500" />
                  {report.recommendations} Action Items
                </span>
              </div>
            </div>
            
            <div className="flex gap-3 border-t border-slate-100 pt-4">
              <button 
                onClick={() => navigate('/assistant')}
                className="flex-1 flex items-center justify-center gap-2 bg-slate-50 hover:bg-slate-100 text-slate-700 py-2.5 rounded-lg font-semibold text-sm transition-colors cursor-pointer"
              >
                <ExternalLink className="w-4 h-4" /> Open in Workspace
              </button>
              <button 
                onClick={() => handleExportReport(report)}
                className="flex-1 flex items-center justify-center gap-2 bg-blue-50 hover:bg-blue-100 text-blue-700 py-2.5 rounded-lg font-semibold text-sm transition-colors cursor-pointer"
              >
                <Download className="w-4 h-4" /> Export Report (.md)
              </button>
            </div>
          </Card>
        ))}
      </div>
    </div>
  );
}
